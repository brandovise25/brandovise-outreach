-- Comment library (Jibran, 21.10.2026): real comments read under LinkedIn posts, Jibran's own and other
-- people's, kept for review. Jibran marks examples good or bad; drafting uses them as style references.
create table if not exists outreach.comment_samples (
  id bigint generated by default as identity primary key,
  comment_urn text,
  post_url text,
  post_author text,
  post_excerpt text,
  author text not null,
  author_profile text,
  author_headline text,
  text text not null,
  reactions int,
  is_reply boolean not null default false,
  reply_to text,
  is_mine boolean not null default false,
  lang text,
  chars int generated always as (char_length(text)) stored,
  label text check (label in ('good', 'bad')),
  note text,
  source text not null default 'robot',
  collected_at timestamptz not null default now(),
  labeled_at timestamptz
);
create unique index if not exists comment_samples_urn on outreach.comment_samples (comment_urn) where comment_urn is not null;
create unique index if not exists comment_samples_text on outreach.comment_samples (coalesce(post_url, ''), author, md5(text));
create index if not exists comment_samples_post on outreach.comment_samples (post_url);
alter table outreach.comment_samples enable row level security;

-- Jibran's own name and profile path, from the newest voice profile read from LinkedIn.
create or replace function outreach.own_identity()
returns jsonb
language sql stable
set search_path = outreach, public
as $$
  select coalesce((select jsonb_build_object(
            'name', lower(samples->'profile'->>'name'),
            'slug', lower(substring(samples->'profile'->>'url' from '/in/([^/?#]+)')))
          from outreach.voice_profiles where status in ('approved', 'replaced', 'draft')
          order by (status = 'approved') desc, created_at desc limit 1), '{}'::jsonb)
$$;

-- Adds the comments read under one post; known ones only get their reaction count refreshed.
create or replace function public.ext_comment_samples_add(p_user_id uuid, p_post jsonb, p_items jsonb, p_source text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  n_new int := 0;
  n_all int := 0;
  i jsonb;
  v_id bigint;
  me jsonb := outreach.own_identity();
begin
  perform outreach.ext_assert_user(p_user_id);
  for i in select * from jsonb_array_elements(coalesce(p_items, '[]')) limit 200 loop
    continue when coalesce(i->>'author', '') = '' or coalesce(i->>'text', '') = '';
    n_all := n_all + 1;
    v_id := null;
    if nullif(i->>'id', '') is not null then
      update outreach.comment_samples set reactions = coalesce((i->>'reactions')::int, reactions)
       where comment_urn = i->>'id' returning id into v_id;
    end if;
    if v_id is null then
      insert into outreach.comment_samples (comment_urn, post_url, post_author, post_excerpt, author, author_profile,
                                            author_headline, text, reactions, is_reply, reply_to, is_mine, lang, source)
      values (nullif(i->>'id', ''), nullif(p_post->>'url', ''), left(p_post->>'author', 200), left(p_post->>'excerpt', 1500),
              left(i->>'author', 200), left(nullif(i->>'profile', ''), 400), left(nullif(i->>'headline', ''), 300),
              left(i->>'text', 3000), (i->>'reactions')::int, coalesce((i->>'reply')::boolean, false),
              left(nullif(i->>'mentions', ''), 200),
              coalesce((i->>'mine')::boolean, false)
                or lower(i->>'author') = me->>'name'
                or lower(substring(i->>'profile' from '/in/([^/?#]+)')) = me->>'slug',
              left(nullif(i->>'lang', ''), 5), left(coalesce(p_source, 'robot'), 40))
      on conflict do nothing
      returning id into v_id;
      if v_id is not null then n_new := n_new + 1; end if;
    end if;
  end loop;
  return jsonb_build_object('ok', true, 'read', n_all, 'added', n_new);
end $$;

-- The library for the app: filter all | mine | others | good | bad | liked, newest posts first.
create or replace function public.ext_comment_samples_list(p_user_id uuid, p_filter text, p_limit int)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'counts', (select jsonb_build_object(
        'all', count(*), 'mine', count(*) filter (where is_mine), 'others', count(*) filter (where not is_mine),
        'good', count(*) filter (where label = 'good'), 'bad', count(*) filter (where label = 'bad'),
        'liked', count(*) filter (where coalesce(reactions, 0) >= 3 and not is_mine),
        'posts', count(distinct post_url))
      from outreach.comment_samples),
    'stats', (select jsonb_build_object(
        'mine_median_chars', percentile_cont(0.5) within group (order by chars) filter (where is_mine),
        'others_median_chars', percentile_cont(0.5) within group (order by chars) filter (where not is_mine),
        'others_liked_median_chars', percentile_cont(0.5) within group (order by chars) filter (where not is_mine and coalesce(reactions, 0) >= 3))
      from outreach.comment_samples),
    'items', (select coalesce(jsonb_agg(to_jsonb(s) order by s.collected_at desc, s.post_url, s.id), '[]') from (
        select id, post_url, post_author, left(post_excerpt, 400) post_excerpt, author, author_profile, author_headline,
               text, reactions, is_reply, reply_to, is_mine, lang, chars, label, note, collected_at
        from outreach.comment_samples
        where case coalesce(p_filter, 'all')
                when 'mine' then is_mine
                when 'others' then not is_mine
                when 'good' then label = 'good'
                when 'bad' then label = 'bad'
                when 'liked' then coalesce(reactions, 0) >= 3 and not is_mine
                else true end
        order by collected_at desc, post_url, id
        limit least(greatest(coalesce(p_limit, 200), 1), 500)) s));
end $$;

create or replace function public.ext_comment_sample_label(p_user_id uuid, p_id bigint, p_label text, p_note text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_label is not null and p_label not in ('good', 'bad') then
    raise exception 'label must be good, bad or empty' using errcode = '22023';
  end if;
  update outreach.comment_samples
     set label = p_label, note = coalesce(left(p_note, 500), note), labeled_at = case when p_label is null then null else now() end
   where id = p_id;
  if not found then raise exception 'unknown comment' using errcode = 'P0002'; end if;
  return jsonb_build_object('ok', true, 'id', p_id, 'label', p_label);
end $$;

-- Style references for drafting: Jibran's good and bad examples first, then well-liked comments by others.
create or replace function public.ext_comment_examples(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'good', (select coalesce(jsonb_agg(jsonb_build_object('text', text, 'lang', lang, 'note', note)), '[]') from (
        select text, lang, note from outreach.comment_samples where label = 'good' order by labeled_at desc limit 8) g),
    'bad', (select coalesce(jsonb_agg(jsonb_build_object('text', text, 'lang', lang, 'note', note)), '[]') from (
        select text, lang, note from outreach.comment_samples where label = 'bad' order by labeled_at desc limit 5) b),
    'liked', (select coalesce(jsonb_agg(jsonb_build_object('text', text, 'lang', lang, 'reactions', reactions)), '[]') from (
        select text, lang, reactions from outreach.comment_samples
        where not is_mine and label is null and coalesce(reactions, 0) >= 3 and not is_reply
        order by reactions desc, collected_at desc limit 6) l));
end $$;

