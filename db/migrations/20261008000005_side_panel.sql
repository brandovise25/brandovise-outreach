-- Side panel: dashboard, approval queue, leads, comment drafts, activity. Additive only.

-- Comment drafts for other people's posts (Engagement Round). Draft only: the extension never posts;
-- "approved" means Jibran will post it himself, "posted" is set when he confirms he did.
create table if not exists outreach.engagement (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  run_id bigint references outreach.runs(id) on delete set null,
  post_urn text,
  post_url text,
  post_excerpt text,
  post_age text,
  author_name text,
  author_headline text,
  author_profile text,
  comment_draft text,
  reason text,
  status text not null default 'drafted' check (status in ('drafted', 'approved', 'posted', 'rejected', 'skipped')),
  reviewed_at timestamptz,
  posted_at timestamptz,
  unique (post_urn)
);
alter table outreach.engagement enable row level security;

-- Today at a glance.
create or replace function public.ext_dashboard(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
declare
  day_start timestamptz := date_trunc('day', now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin';
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'limits', outreach.limits(),
    'usage', (select to_jsonb(u) from outreach.v_today_usage u),
    'ai', jsonb_build_object(
      'today_usd', (select coalesce(sum(cost_usd), 0) from outreach.ai_calls where created_at >= day_start),
      'week_usd', (select coalesce(sum(cost_usd), 0) from outreach.ai_calls where created_at >= now() - interval '7 days'),
      'budget_usd', (outreach.ext_setting('ai_daily_budget_usd') #>> '{}')::numeric),
    'counts', jsonb_build_object(
      'approve', (select count(*) from outreach.action_queue where status = 'proposed'),
      'approved', (select count(*) from outreach.action_queue where status = 'approved'),
      'leads', (select count(*) from outreach.candidates where verdict = 'staged'),
      'comments', (select count(*) from outreach.engagement where status = 'drafted'),
      'replies_open', (select count(*) from outreach.prospects where stage = 'replied' and reply_answered_at is null)),
    'runs', (select coalesce(jsonb_agg(to_jsonb(r) order by r.started_at desc), '[]') from
              (select id, kind, status, started_at, finished_at, left(notes, 200) notes from outreach.runs
               order by started_at desc limit 6) r));
end $$;

-- Rows waiting for Jibran (proposed) or approved and waiting to be sent.
create or replace function public.ext_list_queue(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(x) order by x.status desc, x.action, x.due_at), '[]') from (
    select q.id, q.action, q.step, q.status, q.due_at, q.message_text, q.campaign_id, q.approved_at, q.error,
           p.id as prospect_id, p.full_name, p.first_name, p.headline, p.company, p.linkedin_url, p.stage,
           p.reply_snippet, p.replied_at, p.raw->'fit' as fit, p.raw->'trigger' as trigger
    from outreach.action_queue q join outreach.prospects p on p.id = q.prospect_id
    where q.status in ('proposed', 'approved')
    order by q.due_at limit 200) x);
end $$;

-- Approve, reject or postpone a queue row. Approve never sends; sending is Phase 4.
create or replace function public.ext_review_queue(p_user_id uuid, p_queue_id bigint, p_decision text, p_text text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  q outreach.action_queue;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into q from outreach.action_queue where id = p_queue_id for update;
  if not found then raise exception 'unknown queue row' using errcode = 'P0002'; end if;
  if q.status not in ('proposed', 'approved') then
    raise exception 'row is %, not reviewable', q.status using errcode = '22023';
  end if;
  if p_decision = 'approve' then
    update outreach.action_queue set status = 'approved', approved_at = now(), approved_via = 'extension',
      message_text = coalesce(p_text, message_text) where id = p_queue_id;
  elsif p_decision = 'reject' then
    update outreach.action_queue set status = 'cancelled', error = 'rejected in extension' where id = p_queue_id;
  elsif p_decision = 'later' then
    update outreach.action_queue set status = 'scheduled', approved_at = null, approved_via = null,
      message_text = coalesce(p_text, message_text) where id = p_queue_id;
  elsif p_decision = 'save' then
    update outreach.action_queue set message_text = p_text where id = p_queue_id;
  else
    raise exception 'unknown decision %', p_decision using errcode = '22023';
  end if;
  return jsonb_build_object('ok', true, 'id', p_queue_id, 'decision', p_decision);
end $$;

-- Prospecting candidates waiting for a decision, plus the last 7 days of auto-approved ones.
create or replace function public.ext_list_leads(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(x) order by x.verdict desc, x.found_at desc), '[]') from (
    select c.id, c.found_at, c.full_name, c.headline, c.company, c.linkedin_url, c.segment, c.keyword, c.score,
           c.verdict, c.campaign_id, c.reason
    from outreach.candidates c
    where c.verdict = 'staged' or (c.verdict = 'approved' and c.found_at > now() - interval '7 days')
    order by c.found_at desc limit 200) x);
end $$;

-- Approve a lead: it becomes a prospect in stage 'approved' (the triggers schedule step 1, a connect
-- that still needs Jibran's approval before anything is sent). Reject records the reason.
create or replace function public.ext_review_lead(p_user_id uuid, p_candidate_id bigint, p_decision text, p_campaign_id text, p_reason text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  c outreach.candidates;
  v_url text;
  v_campaign text;
  v_pid bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into c from outreach.candidates where id = p_candidate_id for update;
  if not found then raise exception 'unknown candidate' using errcode = 'P0002'; end if;
  if p_decision = 'reject' then
    update outreach.candidates set verdict = 'rejected',
      reason = concat_ws(' | ', reason, 'rejected in extension: ' || coalesce(nullif(p_reason, ''), 'no reason given'))
    where id = p_candidate_id;
    return jsonb_build_object('ok', true, 'verdict', 'rejected');
  elsif p_decision <> 'approve' then
    raise exception 'unknown decision %', p_decision using errcode = '22023';
  end if;

  v_url := outreach.norm_li_url(c.linkedin_url);
  v_campaign := coalesce(nullif(p_campaign_id, ''), c.campaign_id);
  if v_url is null then raise exception 'candidate has no LinkedIn profile URL' using errcode = '22023'; end if;
  if v_campaign is null or not exists (select 1 from outreach.campaigns where id = v_campaign and status <> 'archived') then
    raise exception 'choose an active campaign' using errcode = '22023';
  end if;
  if exists (select 1 from outreach.prospects where linkedin_url = v_url) then
    update outreach.candidates set verdict = 'duplicate', reason = concat_ws(' | ', reason, 'already a prospect')
    where id = p_candidate_id;
    return jsonb_build_object('ok', true, 'verdict', 'duplicate');
  end if;

  insert into outreach.prospects (linkedin_url, full_name, first_name, last_name, headline, company, segment, score,
                                  campaign_id, stage, source, notes)
  values (v_url, c.full_name, split_part(coalesce(c.full_name, ''), ' ', 1),
          nullif(regexp_replace(coalesce(c.full_name, ''), '^\S+\s*', ''), ''), c.headline, c.company, c.segment, c.score,
          v_campaign, 'approved', 'extension-lead', 'lead approved in extension: ' || coalesce(c.reason, ''))
  returning id into v_pid;
  update outreach.candidates set verdict = 'approved', campaign_id = v_campaign where id = p_candidate_id;
  insert into outreach.events (prospect_id, campaign_id, event_type, detail)
  values (v_pid, v_campaign, 'found', jsonb_build_object('source', 'extension-lead', 'candidate_id', p_candidate_id));
  return jsonb_build_object('ok', true, 'verdict', 'approved', 'prospect_id', v_pid);
end $$;

create or replace function public.ext_list_comments(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(e) order by e.status, e.created_at desc), '[]') from (
    select id, created_at, post_url, post_excerpt, post_age, author_name, author_headline, author_profile,
           comment_draft, reason, status, reviewed_at
    from outreach.engagement
    where status in ('drafted', 'approved') or (status = 'posted' and posted_at > now() - interval '3 days')
    order by created_at desc limit 100) e);
end $$;

create or replace function public.ext_review_comment(p_user_id uuid, p_id bigint, p_decision text, p_text text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_decision not in ('approve', 'reject', 'posted', 'save') then
    raise exception 'unknown decision %', p_decision using errcode = '22023';
  end if;
  update outreach.engagement set
    comment_draft = coalesce(p_text, comment_draft),
    status = case p_decision when 'approve' then 'approved' when 'reject' then 'rejected' when 'posted' then 'posted' else status end,
    reviewed_at = now(),
    posted_at = case when p_decision = 'posted' then now() else posted_at end
  where id = p_id;
  if not found then raise exception 'unknown comment draft' using errcode = 'P0002'; end if;
  return jsonb_build_object('ok', true);
end $$;

-- Timeline of what happened (robot events and runs).
create or replace function public.ext_activity(p_user_id uuid, p_limit int)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(a) order by a.at desc), '[]') from (
    (select 'event' as kind, e.occurred_at as at, e.event_type as type, e.ok, e.campaign_id,
            p.full_name, p.linkedin_url,
            left(coalesce(e.detail->>'note', e.detail->>'error', e.message_text, e.detail->'fit'->>'reason', ''), 200) as note
     from outreach.events e left join outreach.prospects p on p.id = e.prospect_id
     where e.event_type <> 'imported'
     order by e.occurred_at desc limit least(greatest(p_limit, 1), 200))
    union all
    (select 'run', r.started_at, r.kind, r.status in ('ok', 'running'), null, null, null,
            left(coalesce(r.notes, r.status), 200)
     from outreach.runs r order by r.started_at desc limit 30)
  ) a);
end $$;

