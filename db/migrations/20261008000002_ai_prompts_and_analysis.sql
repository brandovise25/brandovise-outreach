-- Target-group text for a campaign: its section in docs.target_groups, else campaigns.description.
create or replace function outreach.ext_target_group(p_campaign_id text)
returns text
language plpgsql stable
set search_path = outreach, public
as $$
declare
  v_doc text := coalesce(outreach.doc('target_groups'), '');
  v_section text;
begin
  v_section := substring(v_doc from '(?s)## ' || regexp_replace(p_campaign_id, '([^a-zA-Z0-9_-])', '\\\1', 'g') || '\s*\n(.*?)(?=\n## |$)');
  if coalesce(trim(v_section), '') <> '' then
    return trim(v_section);
  end if;
  return (select description from outreach.campaigns where id = p_campaign_id);
end $$;

-- The active prompt for a task.
create or replace function public.ext_get_prompt(p_user_id uuid, p_task text)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select jsonb_build_object('task', task, 'version', version, 'model', model, 'fallback_models', fallback_models,
            'system_prompt', system_prompt, 'user_template', user_template, 'json_schema', json_schema,
            'temperature', temperature, 'max_tokens', max_tokens)
          from outreach.ai_prompts where task = p_task and active);
end $$;

-- What the side panel needs to know about the profile that is open: the prospect (if known),
-- its campaign and target group, and stored analysis.
create or replace function public.ext_lookup_prospect(p_user_id uuid, p_linkedin_url text)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
declare
  v_url text := outreach.norm_li_url(p_linkedin_url);
  p outreach.prospects;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into p from outreach.prospects where linkedin_url = v_url;
  if not found then
    return jsonb_build_object('found', false, 'linkedin_url', v_url,
      'campaigns', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'status', status) order by id), '[]')
                    from outreach.campaigns where status <> 'archived'));
  end if;
  return jsonb_build_object('found', true, 'linkedin_url', v_url, 'id', p.id, 'full_name', p.full_name,
    'first_name', p.first_name, 'stage', p.stage, 'campaign_id', p.campaign_id,
    'target_group', case when p.campaign_id is null then null else outreach.ext_target_group(p.campaign_id) end,
    'fit', p.raw->'fit', 'trigger', p.raw->'trigger',
    'campaigns', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'status', status) order by id), '[]')
                  from outreach.campaigns where status <> 'archived'));
end $$;

