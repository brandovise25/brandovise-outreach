-- Saves fit and trigger results into prospects.raw (merged, never overwritten) and logs a visit event.
-- Only for prospects that exist; enrolling new people is Phase 3b.
create or replace function public.ext_save_analysis(
  p_user_id uuid, p_prospect_id bigint, p_fit jsonb, p_trigger jsonb, p_activity jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  v_raw_patch jsonb := '{}';
begin
  perform outreach.ext_assert_user(p_user_id);
  if not exists (select 1 from outreach.prospects where id = p_prospect_id) then
    raise exception 'unknown prospect %', p_prospect_id using errcode = 'P0002';
  end if;
  if p_fit is not null then
    if p_fit->>'status' not in ('yes', 'no', 'unsure') then raise exception 'invalid fit status'; end if;
    v_raw_patch := v_raw_patch || jsonb_build_object('fit', jsonb_build_object(
      'status', p_fit->>'status', 'reason', left(p_fit->>'reason', 300), 'evidence', coalesce(p_fit->'evidence', '[]'),
      'checked_at', now(), 'by', 'extension'));
  end if;
  if p_trigger is not null then
    v_raw_patch := v_raw_patch || jsonb_build_object('trigger',
      coalesce((select raw->'trigger' from outreach.prospects where id = p_prospect_id), '{}')
      || (p_trigger - 'misses') || jsonb_build_object('found_at', now()));
  end if;

  update outreach.prospects set
    raw = coalesce(raw, '{}'::jsonb) || v_raw_patch,
    visited_at = now(),
    activity_checked_at = case when p_activity is not null then now() else activity_checked_at end,
    last_post_at = coalesce((p_activity->>'last_post_at')::timestamptz, last_post_at),
    last_post_url = coalesce(p_activity->>'last_post_url', last_post_url),
    last_post_snippet = coalesce(left(p_activity->>'last_post_snippet', 300), last_post_snippet)
  where id = p_prospect_id;

  insert into outreach.events (prospect_id, campaign_id, event_type, ok, detail)
  select id, campaign_id, 'visit', true, jsonb_build_object('fit', p_fit, 'trigger', p_trigger, 'source', 'extension')
  from outreach.prospects where id = p_prospect_id;

  return jsonb_build_object('ok', true);
end $$;

