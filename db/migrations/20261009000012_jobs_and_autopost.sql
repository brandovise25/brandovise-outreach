-- The remote API (x-api-token) acts as the first enabled user.
create or replace function public.ext_api_user()
returns jsonb
language sql stable security definer
set search_path = outreach, public
as $$
  select to_jsonb(id) from outreach.app_users where enabled order by created_at limit 1
$$;
revoke all on function public.ext_api_user() from public;
grant execute on function public.ext_api_user() to api_rpc;

