-- Remote control (job queue) and auto-posting of approved comments.
-- Jobs are run by the extension, one at a time, each in its own background window.

create table if not exists outreach.ext_jobs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('comment_round', 'post_comment', 'capture_sync')),
  params jsonb not null default '{}',
  status text not null default 'queued' check (status in ('queued', 'running', 'done', 'error', 'cancelled')),
  not_before timestamptz not null default now(),
  created_by text not null default 'panel',
  device_id uuid,
  started_at timestamptz,
  finished_at timestamptz,
  result jsonb
);
create index if not exists ext_jobs_queue on outreach.ext_jobs (status, not_before);
alter table outreach.ext_jobs enable row level security;

create or replace function public.ext_job_enqueue(p_user_id uuid, p_kind text, p_params jsonb, p_not_before timestamptz, p_created_by text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  v_id bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_kind = 'post_comment' and not exists (
       select 1 from outreach.engagement where id = (p_params->>'id')::bigint and status = 'approved') then
    raise exception 'only approved comments can be posted' using errcode = '22023';
  end if;
  insert into outreach.ext_jobs (kind, params, not_before, created_by)
  values (p_kind, coalesce(p_params, '{}'), coalesce(p_not_before, now()), left(coalesce(p_created_by, 'panel'), 40))
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'status', 'queued');
end $$;

-- Hands the extension its next job. One job at a time; a job stuck 'running' for 20 minutes is closed.
-- With nothing queued, the auto-post planner may create a post_comment job (see settings below).
create or replace function public.ext_job_claim(p_user_id uuid, p_device_id uuid)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  j outreach.ext_jobs;
  v_next timestamptz := nullif(outreach.ext_setting('comment_autopost_next') #>> '{}', '')::timestamptz;
  v_hour int := extract(hour from now() at time zone 'Europe/Berlin');
  v_today int;
  v_cand bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.ext_jobs set status = 'error', finished_at = now(), result = jsonb_build_object('note', 'timed out')
  where status = 'running' and started_at < now() - interval '20 minutes';
  if exists (select 1 from outreach.ext_jobs where status = 'running') then
    return null;
  end if;

  -- Auto-post planner: live mode + auto-post on, 07-21 Berlin, under the daily cap, gap elapsed.
  if not exists (select 1 from outreach.ext_jobs where status = 'queued' and not_before <= now())
     and outreach.ext_setting('comment_autopost') = 'true'::jsonb
     and outreach.ext_setting('comment_posting_live') = 'true'::jsonb
     and v_hour >= 7 and v_hour < 21
     and (v_next is null or v_next <= now()) then
    select count(*) into v_today from outreach.ext_jobs
      where kind = 'post_comment' and created_by = 'autopost'
        and created_at >= date_trunc('day', now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin';
    if v_today < coalesce((outreach.ext_setting('comment_autopost_daily_max') #>> '{}')::int, 5) then
      select e.id into v_cand from outreach.engagement e
      where e.status = 'approved'
        and not exists (select 1 from outreach.ext_jobs x where x.kind = 'post_comment'
                        and (x.params->>'id')::bigint = e.id and x.status in ('queued', 'running', 'done'))
      order by e.reviewed_at nulls last, e.id limit 1;
      if v_cand is not null then
        insert into outreach.ext_jobs (kind, params, created_by) values ('post_comment', jsonb_build_object('id', v_cand), 'autopost');
        -- Next auto-post 30-90 minutes later.
        insert into outreach.settings (key, value, note)
        values ('comment_autopost_next', to_jsonb(now() + make_interval(mins => 30 + floor(random() * 61)::int))::text, 'set by the auto-post planner')
        on conflict (key) do update set value = excluded.value, updated_at = now();
      end if;
    end if;
  end if;

  select * into j from outreach.ext_jobs where status = 'queued' and not_before <= now()
  order by not_before, id limit 1 for update skip locked;
  if not found then return null; end if;
  update outreach.ext_jobs set status = 'running', started_at = now(), device_id = p_device_id where id = j.id;
  return jsonb_build_object('id', j.id, 'kind', j.kind, 'params', j.params, 'created_by', j.created_by);
end $$;

create or replace function public.ext_job_finish(p_user_id uuid, p_id bigint, p_status text, p_result jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_status not in ('done', 'error') then raise exception 'status must be done or error' using errcode = '22023'; end if;
  update outreach.ext_jobs set status = p_status, finished_at = now(), result = p_result where id = p_id and status = 'running';
  return jsonb_build_object('ok', found);
end $$;

create or replace function public.ext_job_cancel(p_user_id uuid, p_id bigint)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.ext_jobs set status = 'cancelled', finished_at = now() where id = p_id and status = 'queued';
  return jsonb_build_object('ok', found);
end $$;

create or replace function public.ext_list_jobs(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(j) order by j.id desc), '[]') from
    (select id, kind, params, status, not_before, created_by, created_at, started_at, finished_at, result
     from outreach.ext_jobs order by id desc limit 50) j);
end $$;

-- Auto-post settings: on/off, next time, daily max.
create or replace function public.ext_autopost(p_user_id uuid, p_on boolean)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_on is not null then
    insert into outreach.settings (key, value, note) values ('comment_autopost', p_on::text, 'post approved comments automatically (live mode only)')
    on conflict (key) do update set value = excluded.value, updated_at = now();
  end if;
  return jsonb_build_object(
    'on', coalesce(outreach.ext_setting('comment_autopost') = 'true'::jsonb, false),
    'live', coalesce(outreach.ext_setting('comment_posting_live') = 'true'::jsonb, false),
    'next', outreach.ext_setting('comment_autopost_next') #>> '{}',
    'daily_max', coalesce((outreach.ext_setting('comment_autopost_daily_max') #>> '{}')::int, 5),
    'posted_today', (select count(*) from outreach.ext_jobs where kind = 'post_comment' and created_by = 'autopost'
                     and created_at >= date_trunc('day', now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin'));
end $$;

