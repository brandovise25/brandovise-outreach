-- Live view of what the robot is doing: every job reports its steps (ext_job_events), its current
-- progress (ext_jobs.progress) and can be asked to stop (ext_jobs.stop_requested). All LinkedIn work
-- runs as a job, so the side panel, the remote API and Claude see the same log.

alter table outreach.ext_jobs drop constraint if exists ext_jobs_kind_check;
alter table outreach.ext_jobs add constraint ext_jobs_kind_check check (kind in (
  'comment_round', 'post_comment', 'capture_sync',
  'prospect_round', 'import_leads', 'sync_round', 'send_round'));
alter table outreach.ext_jobs drop constraint if exists ext_jobs_status_check;
