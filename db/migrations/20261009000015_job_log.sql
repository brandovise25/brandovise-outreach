  'queued', 'running', 'done', 'error', 'cancelled', 'stopped'));
alter table outreach.ext_jobs add column if not exists progress jsonb not null default '{}';
alter table outreach.ext_jobs add column if not exists stop_requested boolean not null default false;

create table if not exists outreach.ext_job_events (
  id bigint generated by default as identity primary key,
  job_id bigint not null references outreach.ext_jobs (id) on delete cascade,
  at timestamptz not null default now(),
  level text not null default 'info' check (level in ('info', 'warn', 'error')),
  step text,
  message text not null,
  data jsonb
);
create index if not exists ext_job_events_job on outreach.ext_job_events (job_id, id);
create index if not exists ext_job_events_at on outreach.ext_job_events (at);
alter table outreach.ext_job_events enable row level security;

-- One log line from the extension. Returns whether Jibran asked the job to stop, so the extension
-- learns about a Stop click with its next step. Only a running job can log.
create or replace function public.ext_job_log(p_user_id uuid, p_id bigint, p_level text, p_step text,
  p_message text, p_data jsonb, p_progress jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  v_stop boolean;
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.ext_jobs
     set progress = case when p_progress is null then progress else progress || p_progress end
   where id = p_id and status = 'running'
  returning stop_requested into v_stop;
  if not found then
    return jsonb_build_object('ok', false, 'stop', true);
  end if;
  insert into outreach.ext_job_events (job_id, level, step, message, data)
  values (p_id, case when p_level in ('info', 'warn', 'error') then p_level else 'info' end,
          left(p_step, 60), left(coalesce(p_message, ''), 1000), p_data);
  return jsonb_build_object('ok', true, 'stop', v_stop);
end $$;

-- Stop: a queued job is cancelled; a running one is asked to stop at its next step.
create or replace function public.ext_job_stop(p_user_id uuid, p_id bigint)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.ext_jobs set status = 'cancelled', finished_at = now() where id = p_id and status = 'queued';
  if found then return jsonb_build_object('ok', true, 'state', 'cancelled'); end if;
  update outreach.ext_jobs set stop_requested = true where id = p_id and status = 'running';
  if found then
    insert into outreach.ext_job_events (job_id, level, step, message) values (p_id, 'warn', 'stop', 'Stop requested');
    return jsonb_build_object('ok', true, 'state', 'stopping');
  end if;
  return jsonb_build_object('ok', false);
end $$;

-- The finish call may now also report 'stopped'.
create or replace function public.ext_job_finish(p_user_id uuid, p_id bigint, p_status text, p_result jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_status not in ('done', 'error', 'stopped') then
    raise exception 'status must be done, error or stopped' using errcode = '22023';
  end if;
  update outreach.ext_jobs set status = p_status, finished_at = now(), result = p_result where id = p_id and status = 'running';
  if found then
    insert into outreach.ext_job_events (job_id, level, step, message)
    values (p_id, case p_status when 'error' then 'error' when 'stopped' then 'warn' else 'info' end, 'finish',
            left(coalesce(p_result->>'message', p_status), 1000));
  end if;
  -- Old log lines go after 30 days.
  delete from outreach.ext_job_events where at < now() - interval '30 days';
  return jsonb_build_object('ok', found);
end $$;

-- The robot bar: the running job with its progress and latest lines, what is queued, the last result.
create or replace function public.ext_robot(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
declare
  r outreach.ext_jobs;
  l outreach.ext_jobs;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into r from outreach.ext_jobs where status = 'running' order by started_at desc limit 1;
  select * into l from outreach.ext_jobs where status in ('done', 'error', 'stopped') order by finished_at desc nulls last limit 1;
  return jsonb_build_object(
    'now', now(),
    'running', case when r.id is null then null else jsonb_build_object(
      'id', r.id, 'kind', r.kind, 'params', r.params, 'created_by', r.created_by, 'started_at', r.started_at,
      'progress', r.progress, 'stop_requested', r.stop_requested,
      'events', (select coalesce(jsonb_agg(to_jsonb(e) order by e.id desc), '[]') from
                  (select id, at, level, step, message from outreach.ext_job_events where job_id = r.id order by id desc limit 6) e)) end,
    'queued', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'kind', kind, 'not_before', not_before, 'created_by', created_by) order by not_before, id), '[]')
               from (select * from outreach.ext_jobs where status = 'queued' order by not_before, id limit 10) q),
    'last', case when l.id is null then null else jsonb_build_object(
      'id', l.id, 'kind', l.kind, 'status', l.status, 'finished_at', l.finished_at, 'result', l.result) end);
end $$;

-- Full log of one job, or the latest lines across all jobs.
create or replace function public.ext_job_events(p_user_id uuid, p_job_id bigint, p_limit int)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(e) order by e.id desc), '[]') from
    (select ev.id, ev.job_id, j.kind, ev.at, ev.level, ev.step, ev.message, ev.data
       from outreach.ext_job_events ev join outreach.ext_jobs j on j.id = ev.job_id
      where p_job_id is null or ev.job_id = p_job_id
      order by ev.id desc limit least(greatest(coalesce(p_limit, 200), 1), 1000)) e);
end $$;

