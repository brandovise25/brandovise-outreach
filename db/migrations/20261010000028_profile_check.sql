-- Profile check (10.10.2026): scores Jibran's own LinkedIn profile from what the voice job read
-- (deterministic findings in code) and adds AI rewrites that use only facts from his own texts.
-- Checklist adapted from sergebulaev/linkedin-skills (MIT), skills/linkedin-profile-optimizer.

create table if not exists outreach.profile_checks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  voice_id bigint references outreach.voice_profiles (id) on delete set null,
  findings jsonb not null,
  rewrites jsonb not null
);
alter table outreach.profile_checks enable row level security;

-- the newest samples the robot read (approved, draft or failed voice attempt)
create or replace function public.ext_voice_latest_samples(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select jsonb_build_object('id', id, 'samples', samples, 'created_at', created_at)
          from outreach.voice_profiles where status in ('draft', 'approved', 'failed')
          order by created_at desc limit 1);
end $$;

create or replace function public.ext_profile_check_save(p_user_id uuid, p_voice_id bigint, p_findings jsonb, p_rewrites jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare v_id bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  insert into outreach.profile_checks (voice_id, findings, rewrites) values (p_voice_id, p_findings, p_rewrites)
  returning id into v_id;
  return jsonb_build_object('id', v_id);
end $$;

create or replace function public.ext_profile_check_get(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select to_jsonb(c) || jsonb_build_object('samples_read_at', v.created_at,
                   'posts', (select jsonb_agg(left(p->>'text', 160)) from jsonb_array_elements(v.samples->'posts') p))
          from outreach.profile_checks c left join outreach.voice_profiles v on v.id = c.voice_id
          order by c.id desc limit 1);
end $$;

