-- Posts worth studying: profiles' and feed posts already seen by the robot that are not in the library yet.
create or replace function public.ext_comment_study_plan(p_user_id uuid, p_limit int)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(u), '[]') from (
    select e.post_url u from outreach.engagement e
    where e.post_url like 'https://www.linkedin.com/feed/update/%'
      and not exists (select 1 from outreach.comment_samples s where s.post_url = e.post_url)
    group by e.post_url
    order by bool_or(e.status = 'posted') desc, max(e.created_at) desc
    limit least(greatest(coalesce(p_limit, 10), 1), 30)) x);
end $$;

-- Input for the study: the newest posts in the library with their comments (top-level first, by likes).
create or replace function public.ext_comment_study_input(p_user_id uuid, p_posts int)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(jsonb_build_object(
            'url', p.post_url, 'author', p.post_author, 'excerpt', p.post_excerpt,
            'comments', (select coalesce(jsonb_agg(jsonb_build_object(
                            'text', s.text, 'author', s.author, 'reactions', s.reactions,
                            'is_reply', s.is_reply, 'is_mine', s.is_mine, 'lang', s.lang)
                          order by s.is_mine desc, s.is_reply, s.reactions desc nulls last, s.id), '[]')
                         from (select * from outreach.comment_samples s2 where s2.post_url = p.post_url
                               order by s2.is_mine desc, s2.is_reply, s2.reactions desc nulls last, s2.id limit 15) s))
          order by p.last_at desc), '[]')
          from (select post_url, max(post_author) post_author, max(post_excerpt) post_excerpt, max(collected_at) last_at
                from outreach.comment_samples where post_url is not null
                group by post_url
                having count(*) filter (where not is_mine) >= 2
                order by bool_or(is_mine) desc, max(collected_at) desc
                limit least(greatest(coalesce(p_posts, 30), 1), 60)) p);
end $$;

create or replace function public.ext_comment_study_save(p_user_id uuid, p_posts int, p_comments int, p_stats jsonb,
  p_findings jsonb, p_rules text, p_base_version int)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare v_id bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.comment_studies set status = 'dismissed', decided_at = now() where status = 'ready';
  insert into outreach.comment_studies (posts, comments, stats, findings, proposed_rules, base_rules_version)
  values (p_posts, p_comments, p_stats, p_findings, left(p_rules, 20000), p_base_version)
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

create or replace function public.ext_comment_study_latest(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return coalesce((select to_jsonb(s) || jsonb_build_object(
             'current_rules', outreach.doc('engagement_rules'),
             'current_version', (select max(version) from outreach.docs where doc_key = 'engagement_rules'))
           from outreach.comment_studies s order by s.created_at desc limit 1), 'null'::jsonb);
end $$;

-- Jibran's click: the proposed rules become the new engagement_rules version (the old one stays in the
-- history and can be restored in Settings).
create or replace function public.ext_comment_study_decide(p_user_id uuid, p_id bigint, p_decision text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare s outreach.comment_studies; v int;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into s from outreach.comment_studies where id = p_id for update;
  if not found then raise exception 'unknown study' using errcode = 'P0002'; end if;
  if s.status <> 'ready' then raise exception 'study is %', s.status using errcode = '22023'; end if;
  if p_decision = 'apply' then
    v := outreach.doc_put('engagement_rules', s.proposed_rules, 'comment study #' || s.id || ' applied', 'jibran');
    update outreach.comment_studies set status = 'applied', applied_version = v, decided_at = now() where id = p_id;
    return jsonb_build_object('ok', true, 'status', 'applied', 'version', v);
  elsif p_decision = 'dismiss' then
    update outreach.comment_studies set status = 'dismissed', decided_at = now() where id = p_id;
    return jsonb_build_object('ok', true, 'status', 'dismissed');
  end if;
  raise exception 'decision must be apply or dismiss' using errcode = '22023';
end $$;

