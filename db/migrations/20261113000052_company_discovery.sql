-- Every outside search is counted here: the daily cap for the paid search, and "already searched" for
-- OpenStreetMap, so the same city is not asked again within a week.
create table if not exists outreach.search_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  kind text not null check (kind in ('serper', 'osm')),
  query text not null,
  results int
);
create index if not exists search_log_at on outreach.search_log (kind, at desc);
alter table outreach.search_log enable row level security;
alter table outreach.candidates add column if not exists company_resolved_at timestamptz;

create or replace function public.ext_search_usage(p_user_id uuid)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'cap', coalesce((outreach.ext_setting('search_daily_cap') #>> '{}')::int, 40),
    'used_today', (select count(*) from outreach.search_log where kind = 'serper'
                    and at >= date_trunc('day', now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin'),
    'osm_recent', (select coalesce(jsonb_agg(distinct query), '[]') from outreach.search_log
                    where kind = 'osm' and at > now() - interval '7 days'),
    'recent', (select coalesce(jsonb_agg(to_jsonb(x) order by x.at desc), '[]') from (
                 select kind, query, results, at from outreach.search_log order by at desc limit 15) x));
end $$;

create or replace function public.ext_search_log(p_user_id uuid, p_kind text, p_query text, p_results int)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  insert into outreach.search_log (kind, query, results) values (p_kind, left(p_query, 300), p_results);
  return jsonb_build_object('ok', true);
end $$;

-- Leads found on LinkedIn whose company website is not known yet (each is tried once).
create or replace function public.ext_company_resolve_next(p_user_id uuid, p_limit int)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(x)), '[]') from (
    select c.id, c.full_name, c.company, c.linkedin_url, c.campaign_id, c.segment
    from outreach.candidates c
    where c.verdict in ('staged', 'approved') and c.found_at > now() - interval '14 days'
      and c.company_id is null and c.company_resolved_at is null and coalesce(trim(c.company), '') <> ''
    order by c.found_at desc limit least(greatest(coalesce(p_limit, 3), 1), 10)) x);
end $$;

create or replace function public.ext_company_resolved(p_user_id uuid, p_candidate_id bigint)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.candidates set company_resolved_at = now() where id = p_candidate_id;
  return jsonb_build_object('ok', true);
end $$;

-- Companies whose owner is known from the Impressum and has not been looked up on LinkedIn yet.
-- A company needs a campaign, because the person is checked against that campaign's target group.
create or replace function public.ext_company_lookup_plan(p_user_id uuid, p_limit int)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.companies c set lookup_status = 'no_owner', lookup_at = now()
   where c.profile_status = 'ok' and c.lookup_status is null
     and not exists (select 1 from outreach.observations o where o.company_id = c.id and o.signal_code = 'OWNER_NAME');
  return jsonb_build_object(
    'waiting', (select count(*) from outreach.companies c where c.profile_status = 'ok' and c.lookup_status is null),
    'without_campaign', (select count(*) from outreach.companies c
                          where c.profile_status = 'ok' and c.lookup_status is null and c.campaign_id is null),
    'items', (select coalesce(jsonb_agg(to_jsonb(x)), '[]') from (
      select c.id, c.domain, c.name, c.campaign_id, c.segment,
             (select o.value_text from outreach.observations o
               where o.company_id = c.id and o.signal_code = 'OWNER_NAME' order by o.id limit 1) as owner
      from outreach.companies c join outreach.campaigns ca on ca.id = c.campaign_id and ca.status <> 'archived'
      where c.profile_status = 'ok' and c.lookup_status is null
      order by c.profiled_at limit least(greatest(coalesce(p_limit, 5), 1), 8)) x));
end $$;

create or replace function public.ext_company_lookup_done(p_user_id uuid, p_company_id bigint, p_status text)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.companies set lookup_status = p_status, lookup_at = now() where id = p_company_id;
  return jsonb_build_object('ok', found);
end $$;

-- A campaign for companies that have none yet (chosen later in the Companies list).
create or replace function public.ext_company_set_campaign(p_user_id uuid, p_ids bigint[], p_campaign_id text)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
declare n int;
begin
  perform outreach.ext_assert_user(p_user_id);
  if not exists (select 1 from outreach.campaigns where id = p_campaign_id and status <> 'archived') then
    raise exception 'unknown campaign' using errcode = '22023';
  end if;
  update outreach.companies set campaign_id = p_campaign_id
   where campaign_id is null and (p_ids is null or id = any(p_ids));
  get diagnostics n = row_count;
  return jsonb_build_object('ok', true, 'changed', n);
end $$;

-- The list's counts now also say how many owners wait for the lookup and how many companies have no
-- campaign (the two extra numbers stay when this migration is rolled back; they harm nothing).
create or replace function public.ext_company_list(p_user_id uuid, p_codes text[], p_search text, p_limit int)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'counts', (select jsonb_build_object('all', count(*), 'profiled', count(*) filter (where profile_status = 'ok'),
                 'waiting', count(*) filter (where profiled_at is null), 'blocked', count(*) filter (where profile_status in ('blocked', 'error')),
                 'with_owner', count(*) filter (where exists (select 1 from outreach.observations o where o.company_id = c.id and o.signal_code = 'OWNER_NAME')),
                 'looked_up', count(*) filter (where lookup_status in ('found', 'not_found', 'duplicate')),
                 'to_look_up', count(*) filter (where profile_status = 'ok' and lookup_status is null and exists (
                    select 1 from outreach.observations o where o.company_id = c.id and o.signal_code = 'OWNER_NAME')),
                 'no_campaign', count(*) filter (where campaign_id is null and lookup_status is null))
               from outreach.companies c),
    'codes', (select coalesce(jsonb_agg(jsonb_build_object('code', s.code, 'label', s.label, 'category', s.category,
                 'companies', (select count(distinct o.company_id) from outreach.observations o where o.signal_code = s.code)) order by s.category, s.code), '[]')
              from outreach.signal_codes s),
    'items', (select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc), '[]') from (
        select c.id, c.domain, c.name, c.source, c.city, c.segment, c.campaign_id, c.created_at, c.profiled_at, c.profile_status,
               c.profile_error, c.lookup_status, outreach.company_signals(c.id) as signals,
               (select count(*) from outreach.candidates ca where ca.company_id = c.id) as leads
        from outreach.companies c
        where (coalesce(array_length(p_codes, 1), 0) = 0 or (
                 select count(distinct o.signal_code) from outreach.observations o
                 where o.company_id = c.id and o.signal_code = any(p_codes)) = array_length(p_codes, 1))
          and (coalesce(p_search, '') = '' or c.domain ilike '%' || p_search || '%' or c.name ilike '%' || p_search || '%')
        order by c.created_at desc limit least(greatest(coalesce(p_limit, 100), 1), 300)) x));
end $$;

