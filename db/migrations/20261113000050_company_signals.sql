create or replace function outreach.company_signals(p_company_id bigint)
returns jsonb language sql stable set search_path = outreach, public as $$
  select coalesce(jsonb_agg(jsonb_build_object('code', o.signal_code, 'label', s.label, 'category', s.category,
           'value_text', o.value_text, 'value_num', o.value_num, 'confidence', o.confidence, 'evidence_url', o.evidence_url)
           order by s.category, o.signal_code), '[]')
  from outreach.observations o join outreach.signal_codes s on s.code = o.signal_code
  where o.company_id = p_company_id
$$;

create or replace function public.ext_secret_set(p_user_id uuid, p_name text, p_value text, p_hint text)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if coalesce(p_value, '') = '' then
    delete from outreach.secrets where name = p_name;
    return jsonb_build_object('ok', true, 'set', false);
  end if;
  insert into outreach.secrets (name, value, hint) values (p_name, p_value, left(p_hint, 12))
  on conflict (name) do update set value = excluded.value, hint = excluded.hint, updated_at = now();
  return jsonb_build_object('ok', true, 'set', true);
end $$;
create or replace function public.ext_secret_get(p_user_id uuid, p_name text)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select jsonb_build_object('value', value) from outreach.secrets where name = p_name);
end $$;
create or replace function public.ext_secret_status(p_user_id uuid)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_object_agg(name, jsonb_build_object('hint', hint, 'updated_at', updated_at)), '{}') from outreach.secrets);
end $$;

-- rows: [{domain, name, source, source_ref, city, segment, campaign_id}]
create or replace function public.ext_company_upsert(p_user_id uuid, p_rows jsonb)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
declare n_new int; n_all int;
begin
  perform outreach.ext_assert_user(p_user_id);
  select count(*) into n_all from jsonb_array_elements(coalesce(p_rows, '[]'));
  with ins as (
    insert into outreach.companies (domain, name, source, source_ref, city, segment, campaign_id)
    select lower(x.domain), nullif(left(x.name, 200), ''), coalesce(nullif(x.source, ''), 'manual'), left(x.source_ref, 200),
           left(x.city, 120), left(x.segment, 60),
           (select id from outreach.campaigns where id = x.campaign_id)
    from jsonb_to_recordset(coalesce(p_rows, '[]')) as x(domain text, name text, source text, source_ref text, city text, segment text, campaign_id text)
    where coalesce(x.domain, '') <> ''
    on conflict (domain) do nothing
    returning 1)
  select count(*) into n_new from ins;
  return jsonb_build_object('added', n_new, 'known', n_all - n_new,
    'ids', (select coalesce(jsonb_object_agg(c.domain, c.id), '{}') from outreach.companies c
            where c.domain in (select lower(x->>'domain') from jsonb_array_elements(coalesce(p_rows, '[]')) x)));
end $$;

-- Companies whose site was never read (or more than 90 days ago).
create or replace function public.ext_company_next(p_user_id uuid, p_limit int)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'domain', domain)), '[]') from (
    select id, domain from outreach.companies
    where profiled_at is null or profiled_at < now() - interval '90 days'
    order by profiled_at nulls first, id limit least(greatest(coalesce(p_limit, 5), 1), 20)) x);
end $$;

create or replace function public.ext_company_profiled(p_user_id uuid, p_id bigint, p_status text, p_error text, p_name text, p_observations jsonb)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
declare n int := 0;
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.companies set profiled_at = now(), profile_status = p_status, profile_error = left(p_error, 300),
         name = coalesce(name, nullif(left(p_name, 200), ''))
   where id = p_id;
  if not found then raise exception 'unknown company' using errcode = 'P0002'; end if;
  if p_status = 'ok' then
    delete from outreach.observations where company_id = p_id;
    insert into outreach.observations (company_id, signal_code, value_text, value_num, confidence, evidence_url)
    select p_id, x.code, left(x.value_text, 500), x.value_num, coalesce(x.confidence, 1), left(x.evidence_url, 500)
    from jsonb_to_recordset(coalesce(p_observations, '[]')) as x(code text, value_text text, value_num numeric, confidence numeric, evidence_url text)
    where x.code in (select code from outreach.signal_codes);
    get diagnostics n = row_count;
  end if;
  return jsonb_build_object('ok', true, 'observations', n);
end $$;

-- Ties a LinkedIn person (candidate and prospect rows with this profile URL) to a company.
create or replace function public.ext_company_link(p_user_id uuid, p_company_id bigint, p_linkedin_url text)
returns jsonb language plpgsql security definer set search_path = outreach, public as $$
declare v_url text := outreach.norm_li_url(p_linkedin_url);
begin
  perform outreach.ext_assert_user(p_user_id);
  update outreach.candidates set company_id = p_company_id where linkedin_url = v_url and company_id is distinct from p_company_id;
  update outreach.prospects set company_id = p_company_id where linkedin_url = v_url and company_id is distinct from p_company_id;
  return jsonb_build_object('ok', true);
end $$;

-- Companies for the app; p_codes = signals a company must have (cohort), p_search = part of name/domain.
create or replace function public.ext_company_list(p_user_id uuid, p_codes text[], p_search text, p_limit int)
returns jsonb language plpgsql stable security definer set search_path = outreach, public as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'counts', (select jsonb_build_object('all', count(*), 'profiled', count(*) filter (where profile_status = 'ok'),
                 'waiting', count(*) filter (where profiled_at is null), 'blocked', count(*) filter (where profile_status in ('blocked', 'error')),
                 'with_owner', count(*) filter (where exists (select 1 from outreach.observations o where o.company_id = c.id and o.signal_code = 'OWNER_NAME')),
                 'looked_up', count(*) filter (where lookup_status is not null))
               from outreach.companies c),
    'codes', (select coalesce(jsonb_agg(jsonb_build_object('code', s.code, 'label', s.label, 'category', s.category,
                 'companies', (select count(distinct o.company_id) from outreach.observations o where o.signal_code = s.code)) order by s.category, s.code), '[]')
              from outreach.signal_codes s),
    'items', (select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc), '[]') from (
        select c.id, c.domain, c.name, c.source, c.city, c.segment, c.campaign_id, c.created_at, c.profiled_at, c.profile_status,
               c.profile_error, c.lookup_status, outreach.company_signals(c.id) as signals,
               (select count(*) from outreach.candidates ca where ca.company_id = c.id) as leads
        from outreach.companies c
        where (coalesce(array_length(p_codes, 1), 0) = 0 or (
                 select count(distinct o.signal_code) from outreach.observations o
                 where o.company_id = c.id and o.signal_code = any(p_codes)) = array_length(p_codes, 1))
          and (coalesce(p_search, '') = '' or c.domain ilike '%' || p_search || '%' or c.name ilike '%' || p_search || '%')
        order by c.created_at desc limit least(greatest(coalesce(p_limit, 100), 1), 300)) x));
end $$;

create or replace function public.ext_list_leads(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return (select coalesce(jsonb_agg(to_jsonb(x) order by x.verdict desc, x.found_at desc), '[]') from (
    select c.id, c.found_at, c.full_name, c.headline, c.company, c.linkedin_url, c.segment, c.keyword, c.score,
           c.verdict, c.campaign_id, c.reason, c.company_id,
           (select co.domain from outreach.companies co where co.id = c.company_id) as company_domain,
           outreach.company_signals(c.company_id) as signals
    from outreach.candidates c
    where c.verdict = 'staged' or (c.verdict = 'approved' and c.found_at > now() - interval '7 days')
    order by c.found_at desc limit 200) x);
end $$;

create or replace function public.ext_review_lead(p_user_id uuid, p_candidate_id bigint, p_decision text, p_campaign_id text, p_reason text)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare
  c outreach.candidates;
  v_url text;
  v_campaign text;
  v_pid bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  select * into c from outreach.candidates where id = p_candidate_id for update;
  if not found then raise exception 'unknown candidate' using errcode = 'P0002'; end if;
  if p_decision = 'reject' then
    update outreach.candidates set verdict = 'rejected',
      reason = concat_ws(' | ', reason, 'rejected in extension: ' || coalesce(nullif(p_reason, ''), 'no reason given'))
    where id = p_candidate_id;
    return jsonb_build_object('ok', true, 'verdict', 'rejected');
  elsif p_decision <> 'approve' then
    raise exception 'unknown decision %', p_decision using errcode = '22023';
  end if;

  v_url := outreach.norm_li_url(c.linkedin_url);
  v_campaign := coalesce(nullif(p_campaign_id, ''), c.campaign_id);
  if v_url is null then raise exception 'candidate has no LinkedIn profile URL' using errcode = '22023'; end if;
  if v_campaign is null or not exists (select 1 from outreach.campaigns where id = v_campaign and status <> 'archived') then
    raise exception 'choose an active campaign' using errcode = '22023';
  end if;
  if exists (select 1 from outreach.prospects where linkedin_url = v_url) then
    update outreach.candidates set verdict = 'duplicate', reason = concat_ws(' | ', reason, 'already a prospect')
    where id = p_candidate_id;
    return jsonb_build_object('ok', true, 'verdict', 'duplicate');
  end if;

  insert into outreach.prospects (linkedin_url, full_name, first_name, last_name, headline, company, segment, score,
                                  campaign_id, stage, source, notes, company_id)
  values (v_url, c.full_name, split_part(coalesce(c.full_name, ''), ' ', 1),
          nullif(regexp_replace(coalesce(c.full_name, ''), '^\S+\s*', ''), ''), c.headline, c.company, c.segment, c.score,
          v_campaign, 'approved', 'extension-lead', 'lead approved in extension: ' || coalesce(c.reason, ''), c.company_id)
  returning id into v_pid;
  update outreach.candidates set verdict = 'approved', campaign_id = v_campaign where id = p_candidate_id;
  insert into outreach.events (prospect_id, campaign_id, event_type, detail)
  values (v_pid, v_campaign, 'found', jsonb_build_object('source', 'extension-lead', 'candidate_id', p_candidate_id));
  return jsonb_build_object('ok', true, 'verdict', 'approved', 'prospect_id', v_pid);
end $$;

