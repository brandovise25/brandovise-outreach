create table if not exists outreach.voice_profiles (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  status text not null default 'draft' check (status in ('draft', 'approved', 'replaced', 'rejected')),
  approved_at timestamptz,
  samples jsonb not null,        -- {profile, posts[], comments[]} as read from LinkedIn
  fingerprint jsonb not null,    -- measured in code (sentence length, Sie/du, emoji, dashes, ...)
  profile jsonb not null,        -- AI description of the voice, quotes verified against the samples
  better jsonb not null,         -- AI suggestions: sharper voice rules, profile headline/About ideas
  ai_call_id bigint
);
alter table outreach.voice_profiles enable row level security;

create or replace function public.ext_voice_save(p_user_id uuid, p_samples jsonb, p_fingerprint jsonb,
  p_profile jsonb, p_better jsonb, p_ai_call_id bigint)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
declare v_id bigint;
begin
  perform outreach.ext_assert_user(p_user_id);
  -- one open draft at a time
  update outreach.voice_profiles set status = 'replaced' where status = 'draft';
  insert into outreach.voice_profiles (samples, fingerprint, profile, better, ai_call_id)
  values (p_samples, p_fingerprint, p_profile, p_better, p_ai_call_id) returning id into v_id;
  return jsonb_build_object('id', v_id);
end $$;

create or replace function public.ext_voice_get(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return jsonb_build_object(
    'draft', (select to_jsonb(v) - 'samples' || jsonb_build_object(
                'sample_counts', jsonb_build_object(
                  'posts', jsonb_array_length(coalesce(v.samples->'posts', '[]')),
                  'comments', jsonb_array_length(coalesce(v.samples->'comments', '[]'))))
              from outreach.voice_profiles v where status = 'draft' order by id desc limit 1),
    'approved', (select to_jsonb(v) - 'samples' from outreach.voice_profiles v
                 where status = 'approved' order by approved_at desc limit 1));
end $$;

-- Approve (optionally with Jibran's edits to the profile text); the earlier approved one is replaced.
create or replace function public.ext_voice_decide(p_user_id uuid, p_id bigint, p_decision text, p_profile jsonb)
returns jsonb
language plpgsql security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  if p_decision not in ('approve', 'reject') then
    raise exception 'unknown decision %', p_decision using errcode = '22023';
  end if;
  if p_decision = 'approve' then
    update outreach.voice_profiles set status = 'replaced' where status = 'approved' and id <> p_id;
    update outreach.voice_profiles set status = 'approved', approved_at = now(),
           profile = coalesce(p_profile, profile)
     where id = p_id and status = 'draft';
  else
    update outreach.voice_profiles set status = 'rejected' where id = p_id and status = 'draft';
  end if;
  if not found then raise exception 'no open draft with id %', p_id using errcode = 'P0002'; end if;
  return jsonb_build_object('ok', true);
end $$;

-- The approved voice, as text for drafting prompts ('' when none is approved yet).
create or replace function public.ext_voice_for_drafting(p_user_id uuid)
returns jsonb
language plpgsql stable security definer
set search_path = outreach, public
as $$
begin
  perform outreach.ext_assert_user(p_user_id);
  return coalesce((select jsonb_build_object('profile', profile || jsonb_build_object('better', better), 'fingerprint', fingerprint)
                   from outreach.voice_profiles where status = 'approved' order by approved_at desc limit 1),
                  'null'::jsonb);
end $$;

